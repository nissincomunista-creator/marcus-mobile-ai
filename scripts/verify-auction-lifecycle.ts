assert.equal(catalogVisible(row({availability:check(404)})),false);

const urls = Array.from({length:31},(_,i)=>row({id:String(i),auctionLink:`https://${i%2?'caixa.gov.br':'emgeaimoveis.com.br'}/lote/${i}`}));
const targets=availabilityTargets([...urls,urls[0]]);
assert.equal(targets.length,31,'No 24-link cap or excluded official source');
let concurrent=0,maxConcurrent=0;const hostCounts=new Map<string,number>();
const results:any[]=[];
const fetcher=(async(input:any)=>{
 const host=new URL(input).host;
 concurrent++;maxConcurrent=Math.max(maxConcurrent,concurrent);
 hostCounts.set(host,(hostCounts.get(host)||0)+1);
 assert(hostCounts.get(host)!<=2);
 await new Promise(resolve=>setTimeout(resolve,1));
 concurrent--;hostCounts.set(host,hostCounts.get(host)!-1);
 return new Response('<span class="status">Encerrado</span>',{status:200});
}) as typeof fetch;
const report=await auditAvailability(targets,(_target,result)=>{results.push(result);},fetcher);
assert.equal(report.checked,31);assert.equal(report.retired,31);assert(maxConcurrent<=6);
let blockedRequests=0;
const blockedReport=await auditAvailability(targets,()=>{},(async()=>{blockedRequests++;return new Response('Blocked',{status:403});}) as typeof fetch);
assert.equal(blockedReport.retired,0);assert.equal(blockedReport.unconfirmed,31);
assert(blockedReport.skipped>0 && blockedRequests<=8,'Repeated blocked responses must not flood the same portal');
