assert.equal(check(410).state,'removed');
assert.equal(check(200,'',{finalUrl:'https://example.test/'}).state,'removed');
assert.equal(check(200,'<h1>Imóvel não encontrado</h1>').state,'removed');
assert.equal(check(200,'<div class="alert">Imóvel não está mais disponível para venda</div>').state,'removed');
assert.equal(check(200,'<div class="status">Leilão encerrado</div><script src="recaptcha.js"></script>').state,'closed');
assert.equal(check(200,'<span class="status">Disponível</span><footer>Leilão encerrado</footer>').state,'active');
assert.notEqual(check(200,'<h1>Lote disponível</h1>').state,'removed');
assert.equal(check(200,'<p>Se o leilão for cancelado, o pagamento será devolvido.</p>').state,'unknown');
assert.equal(check(403).state,'unknown');
assert.equal(check(503).state,'unknown');
assert.equal(check(200,'<title>Just a moment</title>').state,'unknown');
assert.equal(check(200,'',{dates:['2026-10-01','2026-10-05']}).status,'expirado_por_data');
